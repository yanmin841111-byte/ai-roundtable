const DICTS: Record<Locale, Record<string, Entry>> = { 'zh-Hant': ZH, en: EN };

let current: Locale = 'zh-Hant';

export function resolveLocale(setting: string | null | undefined): Locale {
  if (setting === 'zh-Hant' || setting === 'en') return setting;
  // 跟隨系統:只有中文語系用繁中,其他一律英文
  const nav = typeof navigator !== 'undefined' ? navigator.language || '' : '';
  return nav.toLowerCase().startsWith('zh') ? 'zh-Hant' : 'en';
}

export function setLocale(locale: Locale): void {
  current = locale;
  if (typeof document !== 'undefined') document.documentElement.lang = locale === 'en' ? 'en' : 'zh-Hant';
}

export function getLocale(): Locale { return current; }

// toLocaleString 用的語系標籤
export function localeTag(): string { return current === 'en' ? 'en-US' : 'zh-TW'; }

// 名稱清單的分隔符:中文用頓號,英文用逗號
export function joinNames(names: string[]): string { return names.join(current === 'en' ? ', ' : '、'); }

export function t(key: string, params: Params = {}): string {
  const entry = DICTS[current][key] ?? ZH[key];
  if (entry == null) return key;
  const text = typeof entry === 'function' ? entry(params) : entry;
  return text.replace(/\{(\w+)\}/g, (m, name: string) => (name in params ? String(params[name]) : m));
}

// 把 index.html 裡標了 data-i18n* 的節點填入目前語言的文案
export function applyStaticText(root: ParentNode = document): void {
  const attrs: Array<[string, (el: HTMLElement, text: string) => void]> = [
    ['data-i18n', (el, text) => { el.textContent = text; }],
    ['data-i18n-title', (el, text) => { el.title = text; }],
    ['data-i18n-placeholder', (el, text) => { el.setAttribute('placeholder', text); }],
    ['data-i18n-aria-label', (el, text) => { el.setAttribute('aria-label', text); }],
  ];
  for (const [attr, apply] of attrs) {
    root.querySelectorAll<HTMLElement>(`[${attr}]`).forEach((el) => {
      const key = el.getAttribute(attr);
      if (key) apply(el, t(key));
    });
  }
}
